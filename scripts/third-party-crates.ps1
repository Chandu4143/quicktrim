# Regenerates docs/third-party-crates.md from the Cargo dependency graph.
#
#   powershell -ExecutionPolicy Bypass -File scripts/third-party-crates.ps1
#
# The list covers every crate Cargo links into the shipped executable
# (normal + build dependencies for the current target), which is what a
# GPL notice needs to account for. Dev-dependencies are excluded because
# they are never distributed.
#
# Cargo's {l} placeholder prints the license field from each crate's
# Cargo.toml. Crates that only ship a license *file* print nothing; those
# are marked "see crate" and must be checked by hand when they appear.

param(
    [string]$Out = "docs/third-party-crates.md"
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Push-Location $root
try {
    $env:PATH = "$env:USERPROFILE\.cargo\bin;$env:PATH"

    $raw = & cargo tree --offline --edges normal,build --prefix none --format "{p}|{l}" 2>$null
    if ($LASTEXITCODE -ne 0) { throw "cargo tree failed" }

    $crates = @{}
    foreach ($line in $raw) {
        $text = ($line -replace '\s*\(\*\)\s*$', '').Trim()
        if (-not $text) { continue }
        $parts = $text -split '\|', 2
        $spec = $parts[0].Trim()
        $license = if ($parts.Count -gt 1) { $parts[1].Trim() } else { "" }
        if (-not $license) { $license = "see crate" }

        # "name v1.2.3" -> name, 1.2.3
        if ($spec -match '^(?<name>\S+) v(?<version>\S+)$') {
            $key = "$($Matches.name) $($Matches.version)"
            $crates[$key] = [pscustomobject]@{
                Name    = $Matches.name
                Version = $Matches.version
                License = $license
            }
        }
    }

    $rows = $crates.Values | Sort-Object Name, Version
    $version = (& cargo metadata --format-version 1 --offline --no-deps 2>$null |
        ConvertFrom-Json).packages[0].version

    $sb = [System.Text.StringBuilder]::new()
    [void]$sb.AppendLine("# Third-party Rust crates")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("Generated by ``scripts/third-party-crates.ps1`` from the Cargo dependency")
    [void]$sb.AppendLine("graph. Do not edit by hand - re-run the script after changing dependencies.")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("This is every crate in QuickTrim $version's build graph: the normal")
    [void]$sb.AppendLine("dependencies linked into the binary, plus build-time dependencies. Both are")
    [void]$sb.AppendLine("listed because a build from source needs both. Dev-dependencies are excluded")
    [void]$sb.AppendLine("because they are never distributed. Cargo's license placeholder reads the")
    [void]$sb.AppendLine("``license`` field of each crate; ``see crate`` means the crate ships a licence")
    [void]$sb.AppendLine("file instead and must be checked by hand.")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("Every crate below uses a license that is compatible with distributing QuickTrim")
    [void]$sb.AppendLine("under the GPLv3: MIT, Apache-2.0, BSD, ISC, Zlib, Unicode-3.0, BSL-1.0, 0BSD,")
    [void]$sb.AppendLine("CC0, Unlicense, or the GPLv3 option of Slint itself. See")
    [void]$sb.AppendLine("[THIRD_PARTY_NOTICES.md](../THIRD_PARTY_NOTICES.md) for the obligations that")
    [void]$sb.AppendLine("follow from that.")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("| Crate | Version | License |")
    [void]$sb.AppendLine("| --- | --- | --- |")
    foreach ($row in $rows) {
        [void]$sb.AppendLine("| $($row.Name) | $($row.Version) | $($row.License) |")
    }
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("$($rows.Count) crates.")

    $path = Join-Path $root $Out
    $dir = Split-Path -Parent $path
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
    # UTF-8 without BOM; Windows PowerShell's Set-Content would add one.
    [System.IO.File]::WriteAllText($path, $sb.ToString(), [System.Text.UTF8Encoding]::new($false))

    "wrote $Out ($($rows.Count) crates)"
}
finally {
    Pop-Location
}
